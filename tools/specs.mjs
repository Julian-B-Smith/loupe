// Turns every loupe-spec block in design/system/components/*/README.md into design/prototype/specs.js, the one module
// the renderer reads design values from (ROADMAP Q-036; Julian, poll 2026-10-30). Deterministic: components in name
// order, keys as written in each block. `--check` exits 1 when the committed module differs; render.test.mjs runs the
// same comparison, which is how `./verify fast` fails on a stale module.
//   node tools/specs.mjs          write the module
//   node tools/specs.mjs --check  compare only
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const OUT = 'design/prototype/specs.js';

export function generate(root = ROOT) {
  const specs = {};
  for (const c of readdirSync(`${root}/design/system/components`).sort()) {
    const f = `${root}/design/system/components/${c}/README.md`;
    if (!existsSync(f)) continue;
    for (const m of readFileSync(f, 'utf8').matchAll(/```loupe-spec\n([\s\S]*?)\n```/g)) {
      const b = JSON.parse(m[1]), key = b.primitive || b.lens;
      if (specs[key]) throw new Error(`two loupe-spec blocks name ${key}`);
      // `notes` are for people only (the schema says never parsed), so they stay in the README.
      const { notes, ...rest } = b;
      specs[key] = rest;
    }
  }
  return '// Generated by tools/specs.mjs from the loupe-spec blocks in design/system/components. Do not edit: edit the\n'
    + '// block, then run `npm run specs`. render.test.mjs fails when this file is stale.\n'
    + `export const SPECS = ${JSON.stringify(specs, null, 1)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate(), path = `${ROOT}/${OUT}`;
  if (process.argv.includes('--check')) {
    const same = existsSync(path) && readFileSync(path, 'utf8') === text;
    console.log(same ? `${OUT}: fresh` : `${OUT}: STALE, run npm run specs`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(path, text);
  console.log(`wrote ${OUT}`);
}
